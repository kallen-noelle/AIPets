import { characterNameKey, characterPersonaKey } from '../chat/types'
import { readStored, writeStored } from '../settings/persisted'

/** Presentation settings shared by every host that renders a character. */
export interface CharacterAppearance {
  scale: number
  /** Horizontal offset in percent of the stage width. */
  offsetX: number
  /** Vertical offset in percent of the stage height. */
  offsetY: number
  fadeMs: number
  mirror: boolean
  clickEnabled: boolean
}

/** Presentation fields shared by built-in characters and imported packs. */
export interface CharacterProfile {
  id: string
  name: string
  roman: string
  role: string
  description: string
  accent: string
  order: number
  appearance: CharacterAppearance
}

/**
 * Entry from `assets/characters.json`.
 *
 * The index is generated by `scripts/build-character-packs.mjs` from the
 * `character.json` inside each `assets/<id>/` folder. Each path is relative to
 * the `/character-assets` root.
 */
export interface BuiltinCharacter extends CharacterProfile {
  manifest: string
  persona?: string
  preview?: string
  clipCount: number
}

export interface CharacterPersona {
  characterName: string
  whisperPrompt: string
}

interface CharacterInput {
  id: string
  name: string
  manifest: string
  persona?: string
  preview?: string
  roman?: string
  role?: string
  description?: string
  accent?: string
  order?: number
  appearance?: unknown
  clipCount?: number
}

export const activeCharacterKey = 'airi:react:character/active'
/** Appearance fields the card page overrides on top of the character folder. */
export const characterAppearanceOverrideKey = 'airi:react:character/appearance-override'
/** Whether the stage shows the character. */
export const characterEnabledKey = 'airi:react:character/enabled'

export type CharacterAppearanceOverride = Partial<CharacterAppearance>

export const defaultCharacterAppearance: CharacterAppearance = {
  scale: 1,
  offsetX: 0,
  offsetY: 0,
  fadeMs: 180,
  mirror: false,
  clickEnabled: true,
}

const assetsBase = './character-assets/'

function isCharacterInput(value: unknown): value is CharacterInput {
  if (typeof value !== 'object' || value === null)
    return false

  const entry = value as Partial<CharacterInput>
  return typeof entry.id === 'string'
    && typeof entry.name === 'string'
    && typeof entry.manifest === 'string'
}

function numberOr(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback
}

function booleanOr(value: unknown, fallback: boolean): boolean {
  return typeof value === 'boolean' ? value : fallback
}

function stringOr(value: unknown, fallback: string): string {
  return typeof value === 'string' && value ? value : fallback
}

export function normalizeAppearance(value: unknown): CharacterAppearance {
  const appearance = typeof value === 'object' && value !== null
    ? value as Record<string, unknown>
    : {}

  return {
    scale: Math.max(0.1, numberOr(appearance.scale, defaultCharacterAppearance.scale)),
    offsetX: numberOr(appearance.offsetX, defaultCharacterAppearance.offsetX),
    offsetY: numberOr(appearance.offsetY, defaultCharacterAppearance.offsetY),
    fadeMs: Math.max(0, numberOr(appearance.fadeMs, defaultCharacterAppearance.fadeMs)),
    mirror: booleanOr(appearance.mirror, defaultCharacterAppearance.mirror),
    clickEnabled: booleanOr(appearance.clickEnabled, defaultCharacterAppearance.clickEnabled),
  }
}

/**
 * Reads the appearance fields the user changed in the card page.
 *
 * Only fields present in the stored object are returned. The stage merges the
 * result over the appearance a character folder ships, so an empty override
 * keeps the original look.
 */
export function readAppearanceOverride(): CharacterAppearanceOverride {
  const stored = readStored<unknown>(characterAppearanceOverrideKey, null)
  if (typeof stored !== 'object' || stored === null)
    return {}

  const entry = stored as Record<string, unknown>
  const override: CharacterAppearanceOverride = {}
  if (typeof entry.scale === 'number' && Number.isFinite(entry.scale))
    override.scale = Math.max(0.1, entry.scale)
  if (typeof entry.offsetX === 'number' && Number.isFinite(entry.offsetX))
    override.offsetX = entry.offsetX
  if (typeof entry.offsetY === 'number' && Number.isFinite(entry.offsetY))
    override.offsetY = entry.offsetY
  if (typeof entry.fadeMs === 'number' && Number.isFinite(entry.fadeMs))
    override.fadeMs = Math.max(0, entry.fadeMs)
  if (typeof entry.mirror === 'boolean')
    override.mirror = entry.mirror
  if (typeof entry.clickEnabled === 'boolean')
    override.clickEnabled = entry.clickEnabled

  return override
}

/**
 * Normalizes a `character.json` shape from a built-in folder or a ZIP pack.
 *
 * Missing fields fall back to the manifest values, so old ZIP packs without a
 * `character.json` still load with default presentation.
 */
export function normalizeCharacterProfile(
  input: unknown,
  fallback: { id: string, name: string },
): CharacterProfile {
  const entry = typeof input === 'object' && input !== null
    ? input as Record<string, unknown>
    : {}

  return {
    id: stringOr(entry.id, fallback.id),
    name: stringOr(entry.name, fallback.name),
    roman: typeof entry.roman === 'string' ? entry.roman : '',
    role: typeof entry.role === 'string' ? entry.role : '',
    description: typeof entry.description === 'string' ? entry.description : '',
    accent: stringOr(entry.accent, '#4fe3c6'),
    order: numberOr(entry.order, 0),
    appearance: normalizeAppearance(entry.appearance),
  }
}

function normalizeCharacter(input: CharacterInput): BuiltinCharacter {
  return {
    ...normalizeCharacterProfile(input, { id: input.id, name: input.name }),
    manifest: input.manifest,
    ...(input.persona ? { persona: input.persona } : {}),
    ...(input.preview ? { preview: input.preview } : {}),
    clipCount: numberOr(input.clipCount, 0),
  }
}

/** Loads the generated index of characters shipped with the app. */
export async function loadBuiltinCharacters(): Promise<BuiltinCharacter[]> {
  const response = await fetch(`${assetsBase}characters.json`)
  if (!response.ok)
    throw new Error(`Cannot load the character index: HTTP ${response.status}`)

  const payload: unknown = await response.json()
  if (!Array.isArray(payload))
    return []

  return payload
    .filter(isCharacterInput)
    .map(normalizeCharacter)
    .sort((left, right) => left.order - right.order || left.id.localeCompare(right.id))
}

/** Chat settings a character pack ships in its `config.json`. */
export interface CharacterChatConfig {
  /** Messages the chat keeps in the model context. */
  historyTurns: number
}

/**
 * Reads the chat settings of one character folder.
 *
 * A missing file, a missing field, or a bad value returns null so the caller
 * keeps its own default.
 */
export async function loadCharacterChatConfig(characterId: string): Promise<CharacterChatConfig | null> {
  try {
    const response = await fetch(`${assetsBase}${characterId}/config.json`)
    if (!response.ok)
      return null

    const payload = await response.json() as { chat?: { historyTurns?: unknown } }
    const turns = payload.chat?.historyTurns
    if (typeof turns !== 'number' || !Number.isFinite(turns) || turns < 2)
      return null

    return { historyTurns: Math.floor(turns) }
  }
  catch {
    return null
  }
}

export function characterManifestUrl(character: BuiltinCharacter): string {
  return `${assetsBase}${character.manifest}`
}

export function characterPreviewUrl(character: BuiltinCharacter): string | undefined {
  return character.preview ? `${assetsBase}${character.preview}` : undefined
}

export function getActiveCharacterId(): string | null {
  const value = readStored<string>(activeCharacterKey, '')
  return typeof value === 'string' && value ? value : null
}

export function setActiveCharacterId(id: string | null) {
  writeStored(activeCharacterKey, id ?? '')
}

/**
 * Reads the persona that belongs to a character folder.
 *
 * The display name comes from `character.json`, so one edit updates every host.
 * A missing file returns null and the chat keeps the persona the user typed.
 */
export async function loadCharacterPersona(character: BuiltinCharacter): Promise<CharacterPersona | null> {
  if (!character.persona)
    return null

  const response = await fetch(`${assetsBase}${character.persona}`)
  if (!response.ok)
    throw new Error(`Cannot load the persona for ${character.id}: HTTP ${response.status}`)

  const payload = await response.json() as { whisperPrompt?: unknown }
  if (typeof payload.whisperPrompt !== 'string')
    return null

  return {
    characterName: character.name,
    whisperPrompt: payload.whisperPrompt,
  }
}

/** Writes the persona into the keys the chat panel reads. */
export function applyCharacterPersona(persona: CharacterPersona) {
  writeStored(characterNameKey, persona.characterName)
  writeStored(characterPersonaKey, persona.whisperPrompt)
}
